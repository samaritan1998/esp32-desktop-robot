"""Rebuild Robot UI Bitmap headers from the pinned OFL-licensed Noto font."""
from pathlib import Path
import argparse
import hashlib
import json
import re
import shutil
import urllib.request
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]


def generate(board, font_path, metadata):
    folder = ROOT/'firmware/boards'/board
    text = '\n'.join((folder/name).read_text() for name in ('face_raster.h', board.split('-')[0]+'_display.h'))
    strings = re.findall(r'"([^"\n]*[\u3400-\u9fff][^"\n]*)"', text)
    chars = sorted({c for c in ''.join(strings) if ord(c) > 127})
    lines = [
        '// SPDX-License-Identifier: OFL-1.1',
        '// Robot UI Bitmap: renamed subset/bitmap conversion of Noto Sans CJK SC.',
        '// '+metadata['copyright'],
        '// Source: '+metadata['url'],
        '// Font SHA256: '+metadata['sha256'],
        '// License: LICENSE.fonts.txt (SIL Open Font License 1.1).',
        '// Generated by tools/generate_glyphs.py; do not edit by hand.',
        '#pragma once', '#include <cstdint>',
        'struct FaceGlyph { uint32_t codepoint; int size; const uint8_t* data; };',
    ]
    table = []
    for size in (16, 18, 28, 36):
        font = ImageFont.truetype(str(font_path), size-1)
        for char in chars:
            im = Image.new('L', (size, size))
            draw = ImageDraw.Draw(im)
            a, b, c, d = draw.textbbox((0, 0), char, font=font)
            draw.text(((size-(c-a))//2-a, (size-(d-b))//2-b), char, font=font, fill=255)
            stride = (size+7)//8
            data = bytearray(stride*size)
            for y in range(size):
                for x in range(size):
                    if im.getpixel((x, y)) >= 105:
                        data[y*stride+x//8] |= 1 << (7-x%8)
            if not any(data):
                raise ValueError(f'Empty glyph: {char!r} at {size}')
            symbol = f'g_{size}_{ord(char):x}'
            lines.append('static const uint8_t '+symbol+'[] = {'+','.join(map(str, data))+'};')
            table.append(f'{{{ord(char)},{size},{symbol}}}')
    lines.append('static const FaceGlyph kFaceGlyphs[] = {'+','.join(table)+'};')
    (folder/'face_glyphs.h').write_text('\n'.join(lines)+'\n')
    shutil.copyfile(ROOT/'LICENSES/OFL-1.1-NotoSansCJK.txt', folder/'LICENSE.fonts.txt')
    print(f'{board}: {len(chars)} characters × 4 sizes = {len(table)} glyphs')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, help='Local unmodified font file; SHA256 is checked')
    args = parser.parse_args()
    metadata = json.loads((ROOT/'firmware/font-source.json').read_text())
    font = args.font or ROOT/'.cache/NotoSansCJKsc-Regular.otf'
    if not font.exists():
        if args.font:
            parser.error('Specified font file does not exist')
        font.parent.mkdir(parents=True, exist_ok=True)
        print('Downloading the pinned OFL font...', flush=True)
        with urllib.request.urlopen(metadata['url'], timeout=120) as response:
            with font.open('wb') as output:
                shutil.copyfileobj(response, output)
    if hashlib.sha256(font.read_bytes()).hexdigest() != metadata['sha256']:
        raise SystemExit('Font checksum mismatch. Remove the incomplete cache or supply the pinned font.')
    for board in ('marvin-183', 'walle-183'):
        generate(board, font, metadata)


if __name__ == '__main__':
    main()
